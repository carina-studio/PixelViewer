namespace Carina.PixelViewer.Media;

/// <summary>
/// Predefined URIs of namespaces of properties of XMP.
/// </summary>
static class XmpNamespaces
{
    /// <summary>
    /// Namespace of properties of Exif which are defined by Adobe.
    /// </summary>
    public const string Aux = "http://ns.adobe.com/exif/1.0/aux/";


    /// <summary>
    /// Namespace of properties defined by Dublin Core.
    /// </summary>
    public const string DC = "http://purl.org/dc/elements/1.1/";


    /// <summary>
    /// Namespace of properties of Exif.
    /// </summary>
    public const string Exif = "http://ns.adobe.com/exif/1.0/";


    /// <summary>
    /// Namespace of properties which were added by Exif 2.3 and later versions.
    /// </summary>
    public const string ExifEx = "http://cipa.jp/exif/1.0/";


    /// <summary>
    /// Namespace of properties defined by Photoshop.
    /// </summary>
    public const string Photoshop = "http://ns.adobe.com/photoshop/1.0/";


    /// <summary>
    /// Namespace of RDF which XMP is based on.
    /// </summary>
    public const string Rdf = "http://www.w3.org/1999/02/22-rdf-syntax-ns#";


    /// <summary>
    /// Namespace of properties of TIFF.
    /// </summary>
    public const string Tiff = "http://ns.adobe.com/tiff/1.0/";


    /// <summary>
    /// Namespace of basic properties of XMP.
    /// </summary>
    public const string Xmp = "http://ns.adobe.com/xap/1.0/";
}
